let language = 'de';
function tr(source, ...values) {
  const message = language === 'en' ? messages[source] ?? source : source;
  return message.replace(/\{(\d+)\}/g, (token, index) => values[index] ?? token);
}
globalThis.piWireTranslate = tr;

function localizeEditor(nextLanguage) {
  language = nextLanguage;
  document.documentElement.lang = language;
  for (const element of document.querySelectorAll('[data-i18n]')) {
    element.textContent = tr(element.dataset.i18n);
  }
  for (const element of document.querySelectorAll('[data-i18n-title]')) {
    element.title = tr(element.dataset.i18nTitle);
  }
  for (const element of document.querySelectorAll('[data-i18n-label]')) {
    element.setAttribute('aria-label', tr(element.dataset.i18nLabel));
  }
  for (const element of document.querySelectorAll('[data-i18n-placeholder]')) {
    element.placeholder = tr(element.dataset.i18nPlaceholder) + ' …';
  }
}
